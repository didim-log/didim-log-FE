const DEFAULT_TITLE_FORMAT = '# 🏆 [백준/BOJ] {{problemId}}번 {{problemTitle}} ({{language}}) {{result}} 회고';

/**
 * 제목 포맷의 플레이스홀더를 실제 값으로 치환
 */
const formatTitle = (format: string, params: {
    problemId: string;
    problemTitle: string;
    language: string;
    result: string;
}): string => {
    return format
        .replace(/\{\{problemId\}\}/g, params.problemId)
        .replace(/\{\{problemTitle\}\}/g, params.problemTitle)
        .replace(/\{\{language\}\}/g, params.language)
        .replace(/\{\{result\}\}/g, params.result);
};

